HALO = 200  # 이 값보다 투명한 픽셀(배경 글로우)은 버린다. 회전 시 잘린 글로우가 선처럼 보임


def poly_mask(pts, size):
    m = Image.new("L", size, 0)
    ImageDraw.Draw(m).polygon(pts, fill=255)
    return np.array(m) > 0


def main():
    im = np.array(Image.open(SRC).convert("RGBA"))
    h, w = im.shape[:2]
    im[im[..., 3] < HALO] = 0
    alpha = im[..., 3] > 0
    taken = np.zeros((h, w), bool)
    masks = {}
    for name, pts in PARTS.items():
        m = poly_mask(pts, (w, h)) & alpha & ~taken
        masks[name] = m
        taken |= m
    masks["base"] = alpha & ~taken
    near = masks["dr_back"] | masks["dr_cush"]

    for name, m in masks.items():
        layer = np.zeros_like(im)
        layer[m] = im[m]
        if name in HIDDEN:
            fill = poly_mask(HIDDEN[name], (w, h)) & ~m & alpha  # 원래 무언가에 가려져 있던 곳만
            if name == "base":
                fill &= near  # 앞좌석 뒤에 숨은 콘솔만
            rgb = cv2.inpaint(np.ascontiguousarray(im[..., :3]), fill.astype(np.uint8) * 255, 9, cv2.INPAINT_TELEA)
            layer[fill, :3] = rgb[fill]
            layer[fill, 3] = 255
        ys, xs = np.nonzero(layer[..., 3])
        x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
        Image.fromarray(layer[y0:y1, x0:x1]).save(f"{OUT}seat_{name}.png", optimize=True)
        print(f'    "{name}" to Offset({x0}f, {y0}f),')


if __name__ == "__main__":
    main()
